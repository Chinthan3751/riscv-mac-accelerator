module instruction_memory (
    input logic [31:0] address,
    output logic [31:0] instruction
);

    logic [31:0] memory [0:255];

    initial begin

        // ========================================
        // MULTIPLE MAC TEST PROGRAM
        // ========================================

        // ----------------------------------------
        // TEST 1
        // x1 = 6
        // x2 = 7
        // x3 = 10
        // ----------------------------------------

        memory[0] = 32'h00600093;   // ADDI x1, x0, 6
        memory[1] = 32'h00700113;   // ADDI x2, x0, 7
        memory[2] = 32'h00A00193;   // ADDI x3, x0, 10

        // MAC x10, x1, x2, x3
        // x10 = 6 * 7 + 10 = 52
        memory[3] = 32'h1820850B;


        // ----------------------------------------
        // TEST 2
        // x4 = 10
        // x5 = 20
        // x6 = 30
        // ----------------------------------------

        memory[4] = 32'h00A00213;   // ADDI x4, x0, 10
        memory[5] = 32'h01400293;   // ADDI x5, x0, 20
        memory[6] = 32'h01E00313;   // ADDI x6, x0, 30

        // MAC x11, x4, x5, x6
        // x11 = 10 * 20 + 30 = 230
        memory[7] = 32'h3052058B;


        // ----------------------------------------
        // TEST 3
        // x7 = 100
        // x8 = 5
        // x9 = 25
        // ----------------------------------------

        memory[8]  = 32'h06400393;  // ADDI x7, x0, 100
        memory[9]  = 32'h00500413;  // ADDI x8, x0, 5
        memory[10] = 32'h01900493;  // ADDI x9, x0, 25

        // MAC x12, x7, x8, x9
        // x12 = 100 * 5 + 25 = 525
        memory[11] = 32'h4883860B;


        // ----------------------------------------
        // NOPs
        // ----------------------------------------

        memory[12] = 32'h00000013;
        memory[13] = 32'h00000013;
        memory[14] = 32'h00000013;
        memory[15] = 32'h00000013;

    end


    always @(*) begin

        instruction = memory[address[9:2]];

    end

endmodule
